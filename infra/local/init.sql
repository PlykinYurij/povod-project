\set ON_ERROR_STOP on
\getenv dev_password DEV_PASSWORD
\getenv test_password TEST_PASSWORD
CREATE ROLE povod_dev LOGIN PASSWORD :'dev_password' NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
CREATE ROLE povod_test LOGIN PASSWORD :'test_password' NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
CREATE DATABASE povod_dev OWNER povod_dev;
CREATE DATABASE povod_test OWNER povod_test;
REVOKE CONNECT, TEMPORARY ON DATABASE povod_dev FROM PUBLIC;
REVOKE CONNECT, TEMPORARY ON DATABASE povod_test FROM PUBLIC;
REVOKE CONNECT ON DATABASE postgres, template1 FROM PUBLIC;
GRANT CONNECT, TEMPORARY ON DATABASE povod_dev TO povod_dev;
GRANT CONNECT, TEMPORARY ON DATABASE povod_test TO povod_test;
\connect povod_dev
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
\connect povod_test
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
